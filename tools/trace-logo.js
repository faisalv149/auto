/*
 * Trace assets/brand/logo.png into an animatable SVG and inline it into the page loader.
 *   car drawing (top)        -> <g class="al-car">  paths with pathLength=1 (draw-on effect)
 *   "ASCEND AUTOS" wordmark  -> <g class="al-word"> one <path class="al-letter"> per letter (staggered rise)
 * Writes assets/brand/logo-animated.svg and fills the LOGO-SVG block in index.html.
 *
 * usage:  npm i potrace@2        (brings jimp with it)
 *         node tools/trace-logo.js
 */
const fs = require('fs');
const path = require('path');
const potrace = require('potrace');
const Jimp = require('jimp');

const root = path.dirname(__dirname);
const SRC = path.join(root, 'assets', 'brand', 'logo.png');
const OUT = path.join(root, 'assets', 'brand', 'logo-animated.svg');
const S = 3;          // trace at 3x for smooth curves, then scale back
const SPLIT = 172;    // row (cropped px) where the car ends and the lettering starts
const ALPHA = 110;    // alpha threshold for "ink"

const traceMask = (img) => new Promise((res, rej) => {
  const t = new potrace.Potrace({ turdSize: 6, alphaMax: 1, optCurve: true, optTolerance: 0.2,
    threshold: 128, turnPolicy: potrace.Potrace.TURNPOLICY_MINORITY });
  t.loadImage(img, (err) => (err ? rej(err) : res(t.getPathTag())));
});
// potrace gives one <path d="M… Z M… Z"> — split into contours, scale back to 1x
const contours = (tag) => {
  const d = (tag.match(/ d="([^"]+)"/) || [])[1] || '';
  return d.split(/(?=M)/).map((s) => s.trim()).filter(Boolean)
    .map((s) => s.replace(/-?\d+(?:\.\d+)?/g, (n) => String(+(n / S).toFixed(1))).replace(/\s+/g, ' ').replace(/ ?([MCLZ]) ?/g, '$1').replace(/ ?, ?/g, ','));
};
const bbox = (d) => {
  const n = (d.match(/-?\d+(?:\.\d+)?/g) || []).map(Number);
  const xs = n.filter((_, i) => i % 2 === 0), ys = n.filter((_, i) => i % 2 === 1);
  return [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
};
const inside = (a, b) => a !== b && a[0] >= b[0] && a[1] >= b[1] && a[2] <= b[2] && a[3] <= b[3];

(async () => {
  const src = await Jimp.read(SRC);
  // crop to the visible logo
  let x0 = src.bitmap.width, y0 = src.bitmap.height, x1 = 0, y1 = 0;
  src.scan(0, 0, src.bitmap.width, src.bitmap.height, function (x, y, i) {
    if (this.bitmap.data[i + 3] > 20) { x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y); }
  });
  const W = x1 - x0 + 1, H = y1 - y0 + 1;
  const big = src.clone().crop(x0, y0, W, H).resize(W * S, H * S, Jimp.RESIZE_BICUBIC);
  const mask = (keep) => {
    const m = new Jimp(W * S, H * S, 0xffffffff);
    big.scan(0, 0, W * S, H * S, function (x, y, i) {
      if (this.bitmap.data[i + 3] > ALPHA && keep(y / S)) m.setPixelColor(0x000000ff, x, y);
    });
    return m;
  };

  const car = contours(await traceMask(mask((y) => y < SPLIT)));
  let word = contours(await traceMask(mask((y) => y >= SPLIT)));
  // the bottoms of the wheels dip just below the split: flat slivers belong to the car, not the lettering
  const flat = (d) => { const b = bbox(d); return b[3] - b[1] < 15; };
  car.push(...word.filter(flat));
  word = word.filter((d) => !flat(d));

  // group wordmark contours into letters (holes belong to the letter whose box contains them)
  const boxes = word.map(bbox);
  const outer = boxes.map((b, i) => i).filter((i) => !boxes.some((b) => inside(boxes[i], b)));
  outer.sort((a, b) => boxes[a][0] - boxes[b][0]);
  const letters = outer.map((i) => [word[i], ...word.filter((_, j) => j !== i && inside(boxes[j], boxes[i]))].join(''));

  const svg = `<svg class="al-logo" viewBox="0 0 ${W} ${H}" xmlns="http://www.w3.org/2000/svg" role="img" aria-label="Ascend Autos">
  <defs>
    <!-- speed lines behind the car fade out to the right, like the original logo -->
    <linearGradient id="al-fade" x1="0" x2="1" y1="0" y2="0"><stop offset=".87" stop-color="#fff"/><stop offset="1" stop-color="#fff" stop-opacity=".12"/></linearGradient>
    <mask id="al-mask" maskUnits="userSpaceOnUse" x="0" y="0" width="${W}" height="${SPLIT}"><rect width="${W}" height="${SPLIT}" fill="url(#al-fade)"/></mask>
    <clipPath id="al-clip"><rect x="0" y="${SPLIT - 4}" width="${W}" height="${H - SPLIT + 8}"/></clipPath>
  </defs>
  <g class="al-car" mask="url(#al-mask)">
${car.map((d) => `    <path class="al-line" pathLength="1" d="${d}"/>`).join('\n')}
  </g>
  <g class="al-word" clip-path="url(#al-clip)">
${letters.map((d, k) => `    <path class="al-letter" style="--i:${k}" fill-rule="evenodd" d="${d}"/>`).join('\n')}
  </g>
</svg>
`;
  fs.writeFileSync(OUT, svg);

  // inline into the loader in index.html so it paints instantly
  const page = path.join(root, 'index.html');
  let html = fs.readFileSync(page, 'utf8');
  const A = '<!-- LOGO-SVG:START (generated by tools/trace-logo.js) -->', B = '<!-- LOGO-SVG:END -->';
  if (html.includes(A) && html.includes(B)) {
    const ind = '      ';
    const block = svg.trim().split('\n').map((l) => ind + l).join('\n');
    html = html.slice(0, html.indexOf(A) + A.length) + '\n' + block + '\n' + ind + html.slice(html.indexOf(B));
    fs.writeFileSync(page, html);
  }
  console.log(`logo-animated.svg: viewBox ${W}x${H}, car contours ${car.length}, letters ${letters.length}, ${(svg.length / 1024).toFixed(1)} KB` + (html.includes(A) ? ', inlined into index.html' : ''));
})().catch((e) => { console.error(e); process.exit(1); });
